/**
 * Scans public/ and writes src/data/manifest.generated.ts.
 *
 * BUILD_BRIEF §11: "generate a small build-time manifest of files actually
 * present in public/frames and public/video so components know upfront what
 * exists" — this is what lets a component decide to render the real scrubber,
 * the procedural fallback, or nothing at all, with no runtime 404 flashes and
 * no code change when an asset is dropped in.
 *
 * Run: node scripts/build-manifest.cjs  (wired into `npm run dev` and `build`)
 */
const fs = require('fs');
const path = require('path');

const PUBLIC = path.join(__dirname, '..', 'public');
const OUT = path.join(__dirname, '..', 'src', 'data', 'manifest.generated.ts');

function list(dir, test) {
  const p = path.join(PUBLIC, dir);
  if (!fs.existsSync(p)) return [];
  return fs.readdirSync(p).filter(test).sort();
}

// frames/<product>/<product>_0001.webp ...
const frames = {};
const framesRoot = path.join(PUBLIC, 'frames');
if (fs.existsSync(framesRoot)) {
  for (const product of fs.readdirSync(framesRoot)) {
    if (!fs.statSync(path.join(framesRoot, product)).isDirectory()) continue;
    const files = list(path.join('frames', product), (f) => /\.(webp|avif|jpg|png)$/i.test(f));
    if (!files.length) continue;
    const ext = path.extname(files[0]).slice(1);
    frames[product] = { count: files.length, ext, pad: 4 };
  }
}

const videos = list('video', (f) => /\.(mp4|webm)$/i.test(f)).map((f) => path.basename(f, path.extname(f)));
const posters = list('posters', (f) => /\.(jpg|jpeg|png|webp)$/i.test(f)).map((f) => path.basename(f, path.extname(f)));
const images = list('img', (f) => /\.(jpg|jpeg|png|webp)$/i.test(f));

const body = `// GENERATED by scripts/build-manifest.cjs — do not edit by hand.
// Regenerated on every dev/build run; reflects what is actually in public/.

export type FrameSequence = { count: number; ext: string; pad: number };

export const FRAME_SEQUENCES: Record<string, FrameSequence> = ${JSON.stringify(frames, null, 2)};

export const VIDEOS: readonly string[] = ${JSON.stringify(videos, null, 2)};

export const POSTERS: readonly string[] = ${JSON.stringify(posters, null, 2)};

export const IMAGES: readonly string[] = ${JSON.stringify(images, null, 2)};
`;

fs.mkdirSync(path.dirname(OUT), { recursive: true });
fs.writeFileSync(OUT, body);

const seqSummary = Object.entries(frames).map(([k, v]) => `${k}:${v.count}`).join(' ') || 'none';
console.log(`manifest: frames[${seqSummary}] videos:${videos.length} posters:${posters.length} images:${images.length}`);
